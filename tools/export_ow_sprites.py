#!/usr/bin/env python3
"""Copy Gen 3 overworld sprites out of a follower sprite pack.

Usage:
    tools/export_ow_sprites.py --source <pack>/Rahtak/Followers --out assets/pokemon_ow

The pack stores one 192x32 sheet per species (six 32x32 frames: down 0-1,
up 2-3, side 4-5), named after the species in lower case with underscores.
This script keeps only the 386 Gen 3 species and renames each sheet to its
numeric id so the mod can look it up without a name table at runtime.

Nothing outside the paths passed on the command line is read or written.
"""

import argparse
import os
import re
import shutil
import sys

try:
    from PIL import Image
except ImportError:
    Image = None

SPECIES_H = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "..", "pokeemerald-expansion", "include", "constants", "species.h",
)

GEN3_LAST = 386


def read_species(header):
    """Return {id: NAME} for the first 386 species."""
    out = {}
    if not os.path.exists(header):
        return out
    pat = re.compile(r"^\s*SPECIES_([A-Z0-9_]+)\s*=\s*(\d+)\s*,")
    with open(header, "r", encoding="utf-8", errors="ignore") as fh:
        for line in fh:
            m = pat.match(line.strip())
            if not m:
                continue
            name, num = m.group(1), int(m.group(2))
            if 1 <= num <= GEN3_LAST and num not in out:
                out[num] = name
    return out


# The pack names the default forms without a suffix.
ALIASES = {
    "castform_normal": "castform",
    "deoxys_normal": "deoxys",
}


def pack_name(name):
    key = name.lower()
    return ALIASES.get(key, key)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", required=True, help="follower sprite folder")
    ap.add_argument("--out", required=True, help="output folder for <id>.png")
    ap.add_argument("--species", default=SPECIES_H, help="path to species.h")
    args = ap.parse_args()

    species = read_species(args.species)
    if not species:
        sys.exit("could not read species list from %s" % args.species)

    if not os.path.isdir(args.source):
        sys.exit("sprite folder not found: %s" % args.source)
    os.makedirs(args.out, exist_ok=True)

    copied, missing = [], []
    for num in sorted(species):
        name = pack_name(species[num])
        src = os.path.join(args.source, name + ".png")
        if not os.path.exists(src):
            missing.append((num, name))
            continue
        dst = os.path.join(args.out, "%d.png" % num)
        if Image is not None:
            # Index 0 is the transparent colour in the pack's sheets; without
            # this the sprites get a solid background in game.
            img = Image.open(src)
            if img.mode == "P":
                # Index 0 is the background.  Write it with black RGB and zero
                # alpha: the game samples these sheets with linear filtering,
                # and a coloured transparent pixel bleeds into the silhouette
                # (it showed up as a blue rim under the sprites).
                pal = img.getpalette()
                src_px = img.load()
                out = Image.new("RGBA", img.size)
                dst_px = out.load()
                for yy in range(img.size[1]):
                    for xx in range(img.size[0]):
                        i = src_px[xx, yy]
                        if i == 0:
                            dst_px[xx, yy] = (0, 0, 0, 0)
                        else:
                            dst_px[xx, yy] = (pal[i * 3], pal[i * 3 + 1], pal[i * 3 + 2], 255)
                out.save(dst)
            else:
                img.convert("RGBA").save(dst)
        else:
            shutil.copyfile(src, dst)
        copied.append(num)

    rows = ["-- Generated by tools/export_ow_sprites.py. Do not edit.",
            "return {"]
    for num in copied:
        rows.append("  [%d] = true," % num)
    rows.append("}")
    lua_path = os.path.join(os.path.dirname(args.out), "..", "data", "ow_sprites.lua")
    lua_path = os.path.normpath(lua_path)
    os.makedirs(os.path.dirname(lua_path), exist_ok=True)
    with open(lua_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(rows) + "\n")

    print("copied %d sprites to %s" % (len(copied), args.out))
    print("wrote %s" % lua_path)
    if missing:
        print("missing %d species (fall back to the 32x32 icon):" % len(missing))
        for num, name in missing[:20]:
            print("  %3d %s" % (num, name))
        if len(missing) > 20:
            print("  ... %d more" % (len(missing) - 20))


if __name__ == "__main__":
    main()
