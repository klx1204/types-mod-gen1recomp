#!/usr/bin/env python3
"""Export Gen 9 tables from a Pokémon Showdown checkout.

This scaffold currently implements the type-chart half. The Pokédex, move and
learnset halves are intentionally left as explicit TODOs so a half-generated
dataset can never be mistaken for a complete one.

Usage:
    python3 tools/export_showdown.py --showdown /path/to/pokemon-showdown
    SHOWDOWN_DIR=/path/to/pokemon-showdown python3 tools/export_showdown.py

The output is written to data/types.lua. No local absolute path is embedded in
the generated file.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

TYPE_NAMES = [
    "NORMAL", "FIGHTING", "FLYING", "POISON", "GROUND", "ROCK", "BUG", "GHOST",
    "STEEL", "CURSE_TYPE", "FIRE", "WATER", "GRASS", "ELECTRIC", "PSYCHIC_TYPE",
    "ICE", "DRAGON", "DARK", "FAIRY",
]

SHOWDOWN_TO_INTERNAL = {
    "Normal": "NORMAL",
    "Fighting": "FIGHTING",
    "Flying": "FLYING",
    "Poison": "POISON",
    "Ground": "GROUND",
    "Rock": "ROCK",
    "Bug": "BUG",
    "Ghost": "GHOST",
    "Steel": "STEEL",
    "Fire": "FIRE",
    "Water": "WATER",
    "Grass": "GRASS",
    "Electric": "ELECTRIC",
    "Psychic": "PSYCHIC_TYPE",
    "Ice": "ICE",
    "Dragon": "DRAGON",
    "Dark": "DARK",
    "Fairy": "FAIRY",
}

# Showdown damageTaken values: 0 normal, 1 weak (2x), 2 resist (0.5x), 3 immune.
MULTIPLIER = {0: 10, 1: 20, 2: 5, 3: 0}


def fail(message: str) -> "None":
    print(f"export_showdown: {message}", file=sys.stderr)
    raise SystemExit(2)


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as exc:
        fail(f"cannot read {path}: {exc}")


def parse_damage_taken(source: str) -> dict[str, dict[str, int]]:
    """Return {defender: {attacker: damageTakenValue}} from typechart.ts.

    The Showdown file is a TypeScript object literal. A small brace-aware
    scanner is enough for the stable `damageTaken` blocks and avoids a
    TypeScript compiler dependency.
    """
    result: dict[str, dict[str, int]] = {}
    type_re = re.compile(r"^\t([a-z]+):\s*\{", re.M)
    for match in type_re.finditer(source):
        name = match.group(1)
        # Find the damageTaken block inside this type entry.
        start = source.find("damageTaken:", match.start())
        if start == -1:
            continue
        brace = source.find("{", start)
        if brace == -1:
            continue
        depth = 0
        end = brace
        for i in range(brace, len(source)):
            if source[i] == "{":
                depth += 1
            elif source[i] == "}":
                depth -= 1
                if depth == 0:
                    end = i
                    break
        block = source[brace + 1:end]
        values: dict[str, int] = {}
        for key, value in re.findall(r"([A-Za-z]+):\s*(\d+)", block):
            if key in ("prankster",):
                continue
            values[key] = int(value)
        if values:
            result[name] = values
    return result


def build_matchups(damage_taken: dict[str, dict[str, int]]) -> list[tuple[str, str, int]]:
    rows: list[tuple[str, str, int]] = []
    for defender, attackers in sorted(damage_taken.items()):
        defender_internal = SHOWDOWN_TO_INTERNAL.get(defender.capitalize())
        if not defender_internal:
            continue
        for attacker, value in sorted(attackers.items()):
            attacker_internal = SHOWDOWN_TO_INTERNAL.get(attacker)
            if not attacker_internal:
                continue
            if value not in MULTIPLIER:
                continue
            rows.append((attacker_internal, defender_internal, MULTIPLIER[value]))
    return rows


def emit_types_lua(rows: list[tuple[str, str, int]], out: Path) -> None:
    index_lines = "\n".join(f"    {name} = {i}," for i, name in enumerate(TYPE_NAMES))
    name_lines = "\n".join(f'    [{i}] = "{name}",' for i, name in enumerate(TYPE_NAMES))
    physical = ", ".join(f"[{i}] = true" for i in range(9))
    matchup_lines = "\n".join(
        f'    {{ attacker = "{a}", defender = "{d}", multiplier = {m} }},'
        for a, d, m in rows
    )
    body = f"""-- Generated by tools/export_showdown.py from Pokémon Showdown.
-- Do not edit by hand. `complete = true` means the full chart is present.
return {{
  complete = true,
  fairyIndex = 18,
  index = {{
{index_lines}
  }},
  names = {{
{name_lines}
  }},
  physical = {{ {physical}, [18] = false }},
  matchups = {{
{matchup_lines}
  }},
}}
"""
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(body, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--showdown", default=os.environ.get("SHOWDOWN_DIR"),
                        help="path to a pokemon-showdown checkout")
    parser.add_argument("--out", default="data/types.lua",
                        help="output Lua file (default: data/types.lua)")
    args = parser.parse_args()

    if not args.showdown:
        fail("pass --showdown <path> or set SHOWDOWN_DIR")
    root = Path(args.showdown).expanduser().resolve()
    chart = root / "data" / "typechart.ts"
    if not chart.is_file():
        fail(f"missing {chart}")

    damage_taken = parse_damage_taken(read_text(chart))
    if "fairy" not in damage_taken:
        fail("typechart.ts did not contain a Fairy entry")
    rows = build_matchups(damage_taken)
    if len(rows) < 300:
        fail(f"only {len(rows)} matchups parsed; refusing to write a partial chart")

    out = Path(args.out)
    emit_types_lua(rows, out)
    print(f"wrote {out} ({len(rows)} matchups)")

    # Explicit TODOs keep a half-generated dataset from looking complete.
    print("TODO: generate data/species_fairy.lua from data/pokedex.ts")
    print("TODO: generate data/move_categories.lua from data/moves.ts")
    print("TODO: generate data/moves_fairy.lua and data/learnsets_fairy.lua")
    print("Until those run, main.lua only applies the type chart plus the")
    print("hand-maintained species and move-type tables.")


if __name__ == "__main__":
    main()
