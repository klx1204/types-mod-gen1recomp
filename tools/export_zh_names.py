#!/usr/bin/env python3
"""Export Chinese species and move names from pokeemerald-expansion.

Usage:
    python3 tools/export_zh_names.py --expansion /path/to/pokeemerald-expansion
    EXPANSION_DIR=/path/to/pokeemerald-expansion python3 tools/export_zh_names.py

Only names are written. Dialog and UI text are handled separately.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path


def fail(message: str) -> "None":
    print(f"export_zh_names: {message}", file=sys.stderr)
    raise SystemExit(1)


def parse_moves(root: Path) -> dict[str, str]:
    path = root / "src" / "data" / "moves_info.h"
    if not path.is_file():
        fail(f"missing {path}")
    text = path.read_text(encoding="utf-8", errors="replace")
    out = {}
    for name, body in re.findall(r"\[MOVE_(\w+)\]\s*=\s*\{(.*?)\n    \},", text, re.S):
        m = re.search(r'\.name\s*=\s*(?:COMPOUND_STRING|_)\("([^"]*)"\)', body)
        if m:
            out[name] = m.group(1).replace("\\n", "").replace("\\p", "")
    return out


def parse_species(root: Path) -> dict[str, str]:
    base = root / "src" / "data" / "pokemon" / "species_info"
    if not base.is_dir():
        fail(f"missing {base}")
    out = {}
    for path in sorted(base.glob("gen_*_families.h")):
        text = path.read_text(encoding="utf-8", errors="replace")
        for name, body in re.findall(r"\[SPECIES_(\w+)\]\s*=\s*\{(.*?)\n    \},", text, re.S):
            m = re.search(r'\.speciesName\s*=\s*(?:COMPOUND_STRING|_)\("([^"]*)"\)', body)
            if m:
                out[name] = m.group(1).replace("\\n", "").replace("\\p", "")
    return out


def emit(species: dict[str, str], moves: dict[str, str], out: Path) -> None:
    def block(title: str, rows: dict[str, str]) -> list[str]:
        lines = [f"  {title} = {{"]
        for key in sorted(rows):
            lines.append('    ["%s"] = "%s",' % (key, rows[key]))
        lines.append("  },")
        return lines

    lines = ["-- Generated by tools/export_zh_names.py from pokeemerald-expansion.",
             "-- Chinese species and move names only; dialog is handled separately.",
             "return {"]
    lines += block("species", species)
    lines += block("moves", moves)
    lines.append("}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--expansion", default=os.environ.get("EXPANSION_DIR"),
                        help="path to a pokeemerald-expansion checkout")
    parser.add_argument("--out", default="data/zh_names.lua")
    args = parser.parse_args()
    if not args.expansion:
        fail("pass --expansion <path> or set EXPANSION_DIR")
    root = Path(args.expansion).expanduser().resolve()
    moves = parse_moves(root)
    species = parse_species(root)
    if len(moves) < 300:
        fail(f"only {len(moves)} move names parsed; refusing a partial table")
    if len(species) < 300:
        fail(f"only {len(species)} species names parsed; refusing a partial table")
    emit(species, moves, Path(args.out))
    print(f"wrote {args.out} ({len(species)} species, {len(moves)} moves)")


if __name__ == "__main__":
    main()
